export function uiValue(value: string, locale?: string | null): string {
  const lang = uiLang(locale);
  if (lang === 'de') return value;
  return value.split(/,\s*/).map(v => VALUE_MAP[v]?.[lang] ?? VALUE_MAP[v]?.en ?? v).join(', ');
}
